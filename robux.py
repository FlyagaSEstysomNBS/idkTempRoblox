import math


def fSolution(a, b, c):
    """
    Функция для решения квадратного уравнения вида ax^2 + bx +  c

    Args:
        a - число перед x^2
        b - число перед x
        c - число без x
    
    Returns:
        Корни уравнения ax^2 + bx + c
    """

    # Считаем дискриминант
    D = b**2 + 4 * a * c

    # Считаем корни с учетом полученого дискриминанта
    x1 = round(-b + math.sqrt(D))
    x2 = round(-b - math.sqrt(D))

    return print(f"Корни квадратного уравнения: x1 - {x1}; x2 - {x2}")


